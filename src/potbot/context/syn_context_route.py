"""Host-only admission for one directed Syn route to the Potbot Context service."""

from __future__ import annotations

import hashlib
import re
import socket
import struct
import sys
import threading
import time
from collections.abc import Callable, Mapping
from dataclasses import dataclass, field
from uuid import UUID, uuid4

from potbot.context.rpc_contract import MAX_FRAME_BYTES, OperationRequest
from potbot.context.rpc_transport import evaluate_context_frame
from potbot.domain.errors import IndeterminateExecutionError, ScopeDeniedError
from potbot.syn_release.contracts import DOCUMENT_LIMIT, canonical, document

METHOD = "context.dispatch"
_DISPATCH = "syn.local-rpc-dispatch/1"
_ACCEPTED = b"potbot.context.accepted/1"
_DISPATCH_FIELDS = {
    "profile",
    "workspace_id",
    "method",
    "request_id",
    "size",
    "boot_id",
    "caller_uid",
}
_HEX32 = re.compile(r"[0-9a-f]{32}\Z")
_HEX64 = re.compile(r"[0-9a-f]{64}\Z")


@dataclass(frozen=True, slots=True)
class WorkerRpcBinding:
    """Facts established by the controller for one already launched worker."""

    workspace_id: UUID
    agent_id: UUID
    invocation_id: UUID
    agent_key_sha256: str
    agent_boot_id: str
    isolation_sha256: str
    lease_id: str
    lease_generation: int

    def __post_init__(self) -> None:
        if (
            not all(
                isinstance(x, UUID) for x in (self.workspace_id, self.agent_id, self.invocation_id)
            )
            or not _HEX64.fullmatch(self.agent_key_sha256)
            or not _HEX32.fullmatch(self.agent_boot_id)
            or not _HEX64.fullmatch(self.isolation_sha256)
            or not self.lease_id
            or type(self.lease_generation) is not int
            or self.lease_generation < 1
        ):
            raise ScopeDeniedError("Invalid native Context invocation binding")


# Installed host code must call the verified Syn client and return its receipt's
# operator boot alongside the reply. This adapter has no direct handler fallback.
type SynRoundTrip = Callable[[UUID, bytes], tuple[bytes, str]]
type ContextHandler = Callable[[OperationRequest], dict[str, object]]


@dataclass(slots=True, eq=False)
class SynContextInvocation:
    route: SynContextRoute
    binding: WorkerRpcBinding
    check_live: Callable[[WorkerRpcBinding], object]
    handler: ContextHandler
    pending: UUID | None = None
    closed: bool = False
    faulted: bool = False
    running: bool = False

    def require_live(self) -> None:
        with self.route._condition:
            if self.closed or self.faulted:
                raise ScopeDeniedError("Syn Context invocation is no longer active")
        if self.check_live(self.binding) is not None:
            raise ScopeDeniedError("Context liveness check must fail by raising")

    def call(self, payload: bytes) -> bytes:
        return self.route._call(self, payload)

    def close(self) -> None:
        # Mark closed before waiting. A handler already inside PostgreSQL must
        # settle before the caller revokes its host-only session capability.
        with self.route._condition:
            self.closed = True
            self.route._condition.wait_for(lambda: not self.running)
            if self.route._invocations.get(self.binding.invocation_id) is self:
                self.route._invocations.pop(self.binding.invocation_id)


@dataclass(slots=True)
class _Pending:
    owner: SynContextInvocation
    size: int
    digest: bytes
    request: bytes | None = field(default=None, repr=False)
    reply: bytes | None = field(default=None, repr=False)


class SynContextRoute:
    """A single pinned operator boot and workspace, owned by the trusted host.

    The transport UUID is generated by the host, separate from the application
    request ID. A request's opaque bytes can occupy the entire Syn payload.
    Only the selected worker channel can enqueue bytes for its Context handler.
    """

    def __init__(
        self,
        *,
        workspace_id: UUID,
        operator_boot: str,
        caller_uid: int,
        round_trip: SynRoundTrip,
    ) -> None:
        if (
            not isinstance(workspace_id, UUID)
            or not _HEX32.fullmatch(operator_boot)
            or type(caller_uid) is not int
            or caller_uid < 0
            or not callable(round_trip)
        ):
            raise ScopeDeniedError("Invalid pinned Syn Context route")
        self.workspace_id, self.operator_boot, self.caller_uid = (
            workspace_id,
            operator_boot,
            caller_uid,
        )
        self._round_trip = round_trip
        self._condition = threading.Condition()
        self._invocations: dict[UUID, SynContextInvocation] = {}
        self._pending: dict[UUID, _Pending] = {}
        self._collections: dict[UUID, UUID] = {}

    def bind(
        self,
        binding: WorkerRpcBinding,
        check_live: Callable[[WorkerRpcBinding], object],
        handler: ContextHandler,
    ) -> SynContextInvocation:
        if binding.workspace_id != self.workspace_id:
            raise ScopeDeniedError("Context invocation differs from the installed workspace")
        owner = SynContextInvocation(self, binding, check_live, handler)
        owner.require_live()
        with self._condition:
            if binding.invocation_id in self._invocations or len(self._invocations) >= 128:
                raise ScopeDeniedError("Context invocation is already bound or exceeds capacity")
            self._invocations[binding.invocation_id] = owner
        return owner

    def _call(self, owner: SynContextInvocation, payload: bytes) -> bytes:
        if type(payload) is not bytes or not 1 <= len(payload) <= MAX_FRAME_BYTES:
            raise ScopeDeniedError("Syn Context frame exceeds its admitted size")
        owner.require_live()
        transport_id, collection_id = uuid4(), uuid4()
        slot = _Pending(owner, len(payload), hashlib.sha256(payload).digest())
        with self._condition:
            if (
                owner.closed
                or owner.faulted
                or owner.pending is not None
                or self._invocations.get(owner.binding.invocation_id) is not owner
            ):
                raise ScopeDeniedError("Syn Context invocation cannot accept another call")
            owner.pending = transport_id
            self._pending[transport_id] = slot
        try:
            accepted, boot = self._round_trip(transport_id, payload)
            if accepted != _ACCEPTED or boot != self.operator_boot:
                raise ScopeDeniedError("Syn did not acknowledge the Context delivery")
            result = self._execute_accepted(slot)
            with self._condition:
                if owner.closed or owner.faulted:
                    raise ScopeDeniedError("Syn Context invocation is no longer active")
                self._collections[collection_id] = transport_id
            reply, boot = self._round_trip(collection_id, transport_id.bytes)
            with self._condition:
                if (
                    type(reply) is not bytes
                    or reply != result
                    or boot != self.operator_boot
                    or collection_id in self._collections
                ):
                    raise ScopeDeniedError("Syn reply does not match the invocation's delivery")
            owner.require_live()
            return reply
        except Exception as exc:
            with self._condition:
                owner.faulted = True
            raise IndeterminateExecutionError(
                "Syn Context exchange failed; reconcile using the original request ID"
            ) from exc
        finally:
            with self._condition:
                owner.pending = None
                self._pending.pop(transport_id, None)
                self._collections.pop(collection_id, None)

    def _execute_accepted(self, slot: _Pending) -> bytes:
        # Syn 0.9.0 bounds each socket exchange to two seconds. Keep native
        # Agent checks and database work between the signed exchanges.
        owner = slot.owner
        with self._condition:
            if slot.request is None or owner.closed or owner.faulted or owner.running:
                raise ScopeDeniedError("Syn did not deliver a live Context request")
            request = slot.request
            owner.running = True
        try:
            owner.require_live()
            reply = evaluate_context_frame(request, owner.handler)
            owner.require_live()
            with self._condition:
                slot.reply = reply
            return reply
        finally:
            with self._condition:
                owner.running = False
                self._condition.notify_all()

    def serve_connection(self, channel: socket.socket, *, operator_uid: int) -> None:
        """Handle one accepted connection on the installer's private service socket."""
        serve_rpc_connection(
            channel, operator_uid=operator_uid, max_payload=MAX_FRAME_BYTES, accept=self.accept
        )

    def accept(self, header: Mapping[str, object], payload: bytes) -> bytes:
        """Accept a dispatch only after the endpoint checks the OS peer is Syn."""
        transport_id = dispatch_id(
            header,
            payload,
            workspace_id=self.workspace_id,
            method=METHOD,
            operator_boot=self.operator_boot,
            caller_uid=self.caller_uid,
            max_payload=MAX_FRAME_BYTES,
        )
        digest = hashlib.sha256(payload).digest()
        with self._condition:
            submission = self._collections.get(transport_id)
            if submission is not None:
                slot = self._pending.get(submission)
                if (
                    payload != submission.bytes
                    or slot is None
                    or slot.reply is None
                    or slot.owner.closed
                    or slot.owner.faulted
                ):
                    raise ScopeDeniedError("Syn collection has no matching live Context result")
                del self._collections[transport_id]
                return slot.reply
            slot = self._pending.get(transport_id)
            if (
                slot is None
                or slot.request is not None
                or slot.size != len(payload)
                or slot.digest != digest
                or slot.owner.closed
                or slot.owner.faulted
                or slot.owner.running
            ):
                raise ScopeDeniedError("Syn dispatch has no matching live Context call")
            slot.request = payload
            return _ACCEPTED


def serve_rpc_connection(
    channel: socket.socket,
    *,
    operator_uid: int,
    max_payload: int,
    accept: Callable[[Mapping[str, object], bytes], bytes],
) -> None:
    if sys.platform != "linux" or channel.family != socket.AF_UNIX:
        raise ScopeDeniedError("Syn RPC service requires native Linux IPC")
    credentials = channel.getsockopt(socket.SOL_SOCKET, socket.SO_PEERCRED, 12)
    _, peer_uid, _ = struct.unpack("iII", credentials)
    if type(operator_uid) is not int or peer_uid != operator_uid:
        raise ScopeDeniedError("RPC service peer is not the installed Syn operator")
    deadline = time.monotonic() + 2

    def set_timeout() -> None:
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            raise TimeoutError("Syn RPC service deadline elapsed")
        channel.settimeout(remaining)

    def read(count: int) -> bytes:
        payload = bytearray()
        while len(payload) < count:
            set_timeout()
            part = channel.recv(count - len(payload))
            if not part:
                raise ScopeDeniedError("Truncated Syn RPC service frame")
            payload.extend(part)
        return bytes(payload)

    (length,) = struct.unpack("!I", read(4))
    if not 1 <= length <= DOCUMENT_LIMIT:
        raise ScopeDeniedError("Syn RPC service header exceeds its bound")
    header = document(read(length), canonical_only=True)
    length = header.get("size")
    if type(length) is not int or not 1 <= length <= max_payload:
        raise ScopeDeniedError("Syn RPC payload exceeds its bound")
    reply = accept(header, read(length))
    metadata = canonical(
        {
            "profile": "syn.local-rpc-service-reply/1",
            "request_id": header["request_id"],
            "size": len(reply),
        }
    )
    set_timeout()
    channel.sendall(struct.pack("!I", len(metadata)) + metadata)
    set_timeout()
    channel.sendall(reply)


def dispatch_id(
    header: Mapping[str, object],
    payload: bytes,
    *,
    workspace_id: UUID,
    method: str,
    operator_boot: str,
    caller_uid: int,
    max_payload: int,
) -> UUID:
    if (
        set(header) != _DISPATCH_FIELDS
        or header["profile"] != _DISPATCH
        or header["workspace_id"] != str(workspace_id)
        or header["method"] != method
        or header["boot_id"] != operator_boot
        or type(header["caller_uid"]) is not int
        or header["caller_uid"] != caller_uid
        or type(header["size"]) is not int
        or type(payload) is not bytes
        or header["size"] != len(payload)
        or not 1 <= len(payload) <= max_payload
        or not isinstance(header["request_id"], str)
    ):
        raise ScopeDeniedError("RPC dispatch differs from the installed Syn route")
    try:
        transport_id = UUID(header["request_id"])
    except ValueError:
        raise ScopeDeniedError("Invalid Syn dispatch ID") from None
    if str(transport_id) != header["request_id"]:
        raise ScopeDeniedError("Invalid Syn dispatch ID")
    return transport_id
